# ========== Задание 1: Сумма квадратов ==========
# Напишите функцию для вычисления суммы квадратов натуральных чисел от a до b,
# где a и b – натуральные числа.

def sum_ab(a, b):
    s = 0
    for i in range(a, b + 1):
        s += i * i
    return s


# Демонстрация использования функции

x, y = 1, 2
print(f'Сумма квадратов чисел от {x} до {y}: {sum_ab(x, y)}')

x, y = 500, 50000
print(f'Сумма квадратов чисел от {x} до {y}: {sum_ab(x, y)}')

x, y = 268, 3258
print(f'Сумма квадратов чисел от {x} до {y}: {sum_ab(x, y)}')


# ========== Индивидуальное задание ==========
# Напишите функцию, которая печатает таблицу значений функции
# y = x^2 + 3*x^3 для x ∈ [0, 10].
# Таблица печатает значения только для целых значений x с шагом 1.

def f(x):
    """Вычисление значения функции y = x^2 + 3*x^3"""
    return x**2 + 3 * x**3


def print_table():
    """Печать таблицы значений функции y = x^2 + 3*x^3 для x от 0 до 10"""
    print(f"{'x':>5} | {'y = x² + 3·x³':>15}")
    print("-" * 25)
    for x in range(0, 11):
        y = f(x)
        print(f"{x:>5} | {y:>15}")


print("\nТаблица значений функции y = x² + 3·x³:")
print_table()
